def _paeth_predictor(left, up, up_left):
    """Pick the Paeth predictor: whichever of left/up/up-left the
    straight-line estimate ``left + up - up_left`` is closest to."""
    estimate = left + up - up_left
    dist_left = abs(estimate - left)
    dist_up = abs(estimate - up)
    dist_up_left = abs(estimate - up_left)
    if dist_left <= dist_up and dist_left <= dist_up_left:
        return left
    if dist_up <= dist_up_left:
        return up
    return up_left


def _filter_row(kind, row, prev):
    """Return one scanline filtered with PNG filter ``kind``.

    ``row`` and ``prev`` are the raw bytes of this row and the row
    above it.  Filter 0 is None, 1 is Sub, 2 is Up, 3 is Average and
    4 is Paeth.  A missing neighbour (first row / first pixel) counts
    as zero.
    """
    out = bytearray(ROW_LEN)
    if kind == 0:
        out[:] = row
    elif kind == 1:  # Sub: difference from the pixel to the left
        for i in range(ROW_LEN):
            left = row[i - CHANNELS] if i >= CHANNELS else 0
            out[i] = (row[i] - left) & 0xFF
    elif kind == 2:  # Up: difference from the pixel above
        for i in range(ROW_LEN):
            out[i] = (row[i] - prev[i]) & 0xFF
    elif kind == 3:  # Average: difference from the mean of left/up
        for i in range(ROW_LEN):
            left = row[i - CHANNELS] if i >= CHANNELS else 0
            out[i] = (row[i] - ((left + prev[i]) >> 1)) & 0xFF
    else:  # Paeth
        for i in range(ROW_LEN):
            left = row[i - CHANNELS] if i >= CHANNELS else 0
            up = prev[i]
            up_left = prev[i - CHANNELS] if i >= CHANNELS else 0
            guess = _paeth_predictor(left, up, up_left)
            out[i] = (row[i] - guess) & 0xFF
    return out


def _filter_cost(filtered):
    """How well a filtered row should compress: the sum of the
    absolute values of its bytes read as signed (-128..127).  Small
    values and long zero runs score low."""
    total = 0
    for byte in filtered:
        total += byte if byte < 128 else 256 - byte
    return total


def _best_filter(row, prev):
    """Try every filter on this row and keep the cheapest one.
    Filters are tried in order 0..4 and a tie keeps the earlier one,
    so the choice is fully deterministic."""
    best_kind = 0
    best_cost = None
    for kind in range(5):
        cost = _filter_cost(_filter_row(kind, row, prev))
        if best_cost is None or cost < best_cost:
            best_cost = cost
            best_kind = kind
    return best_kind


def _chunk(kind, data):
    """One PNG chunk: length, type, data, CRC32 over type + data."""
    body = kind + data
    return struct.pack(">I", len(data)) + body + struct.pack(
        ">I", zlib.crc32(body) & 0xFFFFFFFF
    )


def _encode_png(pixels):
    """Assemble the complete PNG file for 1024x1024 RGB pixels."""
    filtered = bytearray()
    prev = bytes(ROW_LEN)
    for y in range(HEIGHT):
        row = pixels[y * ROW_LEN:(y + 1) * ROW_LEN]
        kind = _best_filter(row, prev)
        filtered.append(kind)
        filtered += _filter_row(kind, row, prev)
        prev = row

    compressor = zlib.compressobj(
        9, zlib.DEFLATED, 15, 9, zlib.Z_FILTERED
    )
    compressed = compressor.compress(bytes(filtered)) + compressor.flush()

    header = struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0)
    png = bytearray(b"\x89PNG\r\n\x1a\n")
    png += _chunk(b"IHDR", header)
    # IDAT data goes out in 65536-byte pieces, one chunk per piece.
    for start in range(0, len(compressed), 65536):
        png += _chunk(b"IDAT", compressed[start:start + 65536])
    png += _chunk(b"IEND", b"")
    return bytes(png)


def _load_pixels():
    """Decode the embedded pixel block and check its size."""
    raw = zlib.decompress(
        base64.b64decode("".join(_PIXELS_B64.split()))
    )
    if len(raw) != WIDTH * HEIGHT * CHANNELS:
        raise ValueError(
            "pixel block has %d bytes, expected %d"
            % (len(raw), WIDTH * HEIGHT * CHANNELS)
        )
    return raw


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(out_dir, "entry.png")
    with open(target, "wb") as handle:
        handle.write(_encode_png(_load_pixels()))
    print("wrote %s" % target)


if __name__ == "__main__":
    main()
